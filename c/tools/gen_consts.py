#!/usr/bin/env python3
"""Generate src/s_gen.h (constants) from ../src/consts.txt and the builtin
word list of ../src/a_head.crexx.   usage: python3 tools/gen_consts.py > src/s_gen.h"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
sd = os.path.join(here, '..', '..', 'src')
out = ['/* generated by tools/gen_consts.py - do not edit */']
for line in open(os.path.join(sd, 'consts.txt')):
    line = line.split('#')[0].strip()
    if line:
        k, v = line.split()
        out.append('#define %s %s' % (k, v))
m = re.search(r'bfn = "([^"]*)"', open(os.path.join(sd, 'a_head.crexx')).read())
words = m.group(1).split()
for i, w in enumerate(words):
    out.append('#define FN_%s %d' % (w, i + 1))
out.append('#define BFN_COUNT %d' % len(words))
out.append('static const char *const bfn_w[] = {')
out.append('  ""' + ''.join(',\n  "%s"' % w for w in words))
out.append('};')
print('\n'.join(out))
